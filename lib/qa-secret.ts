const LEAKED = 'psycho-qa-2026';

export function qaSecretOk(provided: string | null): boolean {
  const expected = process.env.QA_SECRET;
  if (!expected) return false;
  if (expected === LEAKED) return false;   // הערך הדלוף אינו פותח, גם אם הוא מוגדר
  if (!provided) return false;
  return provided === expected;
}

// הודעה שאומרת מה לעשות, כדי שהחסימה לא תיקרא כתקלה
export const QA_SECRET_HINT =
  process.env.QA_SECRET === LEAKED
    ? 'QA_SECRET is the value that leaked into the public repository. Rotate it in Vercel and redeploy.'
    : undefined;
